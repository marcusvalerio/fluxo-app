type TranslationKey = keyof typeof translations.pt

interface I18nContextType {
  locale: Locale
  t: (key: TranslationKey) => string
  setLocale: (locale: Locale) => void
}

const I18nContext = createContext<I18nContextType | null>(null)

function detectBrowserLocale(): Locale {
  const lang = navigator.language || "pt"
  if (lang.startsWith("pt")) return "pt"
  if (lang.startsWith("es")) return "es"
  return "en"
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const { user } = useAuth()
  const [locale, setLocaleState] = useState<Locale>("pt")

  useEffect(() => {
    // Tentar carregar preferência salva no Supabase
    if (user) {
      supabase.from("profiles").select("locale").eq("id", user.id).single()
        .then(({ data }) => {
          if (data?.locale) {
            setLocaleState(data.locale as Locale)
          } else {
            setLocaleState(detectBrowserLocale())
          }
        })
    } else {
      setLocaleState(detectBrowserLocale())
    }
  }, [user])

  const setLocale = async (newLocale: Locale) => {
    setLocaleState(newLocale)
    if (user) {
      await supabase.from("profiles").update({ locale: newLocale }).eq("id", user.id)
    }
  }

  const t = (key: TranslationKey): string => {
    return translations[locale][key] || translations.pt[key] || key
  }

  return (
    <I18nContext.Provider value={{ locale, t, setLocale }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error("useI18n must be used within I18nProvider")
  return ctx
}
